/**
 * Sign-in backdrops: photos → WebP plates + src/features/auth/backdrops.js.
 *
 *   node scripts/build-auth-bg.mjs "<folder with the photos>"
 *
 * One plate is picked at random on each visit to the sign-in page. Every photo
 * is from Unsplash under the Unsplash License (free to use); the credits below
 * are written into backdrops.js. For each photo:
 *   public/auth-bg/<name>.webp     1920×1080, wide screens
 *   public/auth-bg/<name>-m.webp   720×1280, phones
 * cropped around the most detailed part (sharp's "attention" strategy).
 */
import sharp from 'sharp';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-auth-bg.mjs <photo folder>'); process.exit(1); }

const PHOTOS = [
  { name: 'monstera', title: 'Monstera leaves', by: 'wallace Henry', url: 'https://unsplash.com/photos/epx0jN-9YrQ' },
  { name: 'milkyway-mountains', title: 'Milky Way over mountains', by: 'Filip Kvasnak', url: 'https://unsplash.com/photos/UeRIcbTthwE' },
  { name: 'milkyway-clouds', title: 'Milky Way above the clouds', by: 'Chan Hoi', url: 'https://unsplash.com/photos/uj-w-v7OFT4' },
  { name: 'moon-sea', title: 'Moon over the sea', by: 'Garrett Schmid', url: 'https://unsplash.com/photos/HMnWtsGsUMg' },
  { name: 'moonlit-waves', title: 'Moonlit waves', by: 'Davide Sibilio', url: 'https://unsplash.com/photos/quOy9JPjEKs' },
  { name: 'earth-space', title: 'A planet in space', by: 'Aman Pal', url: 'https://unsplash.com/photos/Ccr1f7xxzMg' },
  { name: 'milkyway-ridge', title: 'Milky Way above a ridge', by: 'wallace Henry', url: 'https://unsplash.com/photos/wBh-XzDmyIE' },
];

const vignette = (w, h) => Buffer.from(`<svg width="${w}" height="${h}" xmlns="http://www.w3.org/2000/svg">
  <defs><radialGradient id="v" cx="0.5" cy="0.5" r="0.75">
    <stop offset="0.55" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="0.6"/>
  </radialGradient></defs><rect width="100%" height="100%" fill="url(#v)"/></svg>`);

await rm('public/auth-bg', { recursive: true, force: true });
await mkdir('public/auth-bg', { recursive: true });
const out = [];
for (const p of PHOTOS) {
  const src = path.join(dir, `${p.name}.jpg`);
  const plate = async (w, h, file, q) => {
    await sharp(src).resize(w, h, { fit: 'cover', position: sharp.strategy.attention }).modulate({ brightness: 0.86 })
      .composite([{ input: vignette(w, h) }]).webp({ quality: q, effort: 6 }).toFile(`public/auth-bg/${file}`);
  };
  await plate(1920, 1080, `${p.name}.webp`, 72);
  await plate(720, 1280, `${p.name}-m.webp`, 70);
  const lqip = await sharp(`public/auth-bg/${p.name}.webp`).resize(20, 11).webp({ quality: 40 }).toBuffer();
  out.push({ ...p, desktop: `/auth-bg/${p.name}.webp`, mobile: `/auth-bg/${p.name}-m.webp`, lqip: `data:image/webp;base64,${lqip.toString('base64')}` });
  console.log('built', p.name);
}
await writeFile('src/features/auth/backdrops.js', `/**
 * Sign-in backdrops (generated by scripts/build-auth-bg.mjs; edit the script, not this file).
 * Photos from Unsplash, free to use under the Unsplash License: https://unsplash.com/license
 */
export const BACKDROPS = ${JSON.stringify(out, null, 2)};

/** A different backdrop on each visit, never the same one twice in a row. */
export function pickBackdrop() {
  let last = -1;
  try { last = Number(sessionStorage.getItem('fx-auth-bg') ?? -1); } catch { /* storage blocked */ }
  let i = Math.floor(Math.random() * BACKDROPS.length);
  if (BACKDROPS.length > 1 && i === last) i = (i + 1) % BACKDROPS.length;
  try { sessionStorage.setItem('fx-auth-bg', String(i)); } catch { /* storage blocked */ }
  return BACKDROPS[i];
}
`);
console.log('wrote src/features/auth/backdrops.js');
