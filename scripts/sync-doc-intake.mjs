#!/usr/bin/env node
/**
 * The doc-intake Edge Function is deployed self-contained, so it carries a GENERATED copy of the exact
 * parsers the rest of the app uses (same idea as the portfolio-snapshot engine):
 *   src/lib/psx/confirmations.js, src/lib/psx/dividends.js  → supabase/functions/doc-intake/vendor/psx/
 *   supabase/functions/_shared/mf/pdfRows.js, parsers/* → supabase/functions/doc-intake/vendor/mf/
 *
 *   node scripts/sync-doc-intake.mjs          # write the copies
 *   node scripts/sync-doc-intake.mjs --check  # exit 1 if any copy drifted (run by scripts/psx/doc-intake.test.mjs)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fn = join(root, 'supabase/functions/doc-intake/vendor');
const BANNER = '// GENERATED by scripts/sync-doc-intake.mjs — do not edit; edit the source and re-run the script.\n';

const parsers = readdirSync(join(root, 'supabase/functions/_shared/mf/parsers')).filter((f) => f.endsWith('.js'));
const PAIRS = [
  ['src/lib/psx/confirmations.js', 'psx/confirmations.js'],
  ['src/lib/psx/dividends.js', 'psx/dividends.js'],
  ['supabase/functions/_shared/mf/pdfRows.js', 'mf/pdfRows.js'],
  ...parsers.map((f) => [`supabase/functions/_shared/mf/parsers/${f}`, `mf/parsers/${f}`]),
];

const check = process.argv.includes('--check');
const drift = [];
for (const [src, dst] of PAIRS) {
  const want = BANNER + readFileSync(join(root, src), 'utf8');
  const out = join(fn, dst);
  if (check) {
    // Compare with line endings normalised: on Windows (core.autocrlf) git checks files out with CRLF.
    const lf = (t) => t.replace(/\r\n/g, '\n');
    if (!existsSync(out) || lf(readFileSync(out, 'utf8')) !== lf(want)) drift.push(dst);
    continue;
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, want);
}
if (check) {
  if (drift.length) { console.error(`doc-intake vendor copies are stale: ${drift.join(', ')} — run node scripts/sync-doc-intake.mjs`); process.exit(1); }
  console.log('doc-intake vendor copies are in sync.');
} else {
  console.log(`Wrote ${PAIRS.length} files to supabase/functions/doc-intake/vendor/.`);
}
