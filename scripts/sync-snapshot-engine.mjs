/**
 * Copy the engines the snapshot job needs into the Edge Function, so the
 * nightly snapshots are computed by exactly the code the screens use.
 *
 *   node scripts/sync-snapshot-engine.mjs           write the copies
 *   node scripts/sync-snapshot-engine.mjs --check   exit 1 if a copy differs (run by the unit tests)
 *
 * Only import paths are rewritten (the function folder is flat).
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const FILES = [
  ['src/lib/mf/profit.js', 'profit.js'],
  ['src/lib/psx/portfolio.js', 'portfolio.js'],
  ['src/lib/home/combine.js', 'combine.js'],
  ['src/lib/snapshots/build.js', 'build.js'],
];
const OUT = 'supabase/functions/portfolio-snapshot/engine';
const HEADER = '// GENERATED by scripts/sync-snapshot-engine.mjs from the app source. Do not edit here.\n';
const rewrite = (src) => HEADER + src
  .replace("from '../mf/profit.js'", "from './profit.js'")
  .replace("from '../psx/portfolio.js'", "from './portfolio.js'")
  .replace("from '../home/combine.js'", "from './combine.js'");

export async function expected() {
  return Promise.all(FILES.map(async ([from, to]) => [`${OUT}/${to}`, rewrite(await readFile(from, 'utf8'))]));
}

if (process.argv[1]?.endsWith('sync-snapshot-engine.mjs')) {
  const check = process.argv.includes('--check');
  let stale = 0;
  if (!check) await mkdir(OUT, { recursive: true });
  for (const [file, content] of await expected()) {
    if (check) {
      const have = await readFile(file, 'utf8').catch(() => null);
      if (have?.replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) { console.error(`stale: ${file}`); stale += 1; }
    } else {
      await writeFile(file, content);
      console.log('wrote', file);
    }
  }
  if (stale) { console.error('Run: node scripts/sync-snapshot-engine.mjs'); process.exit(1); }
}
