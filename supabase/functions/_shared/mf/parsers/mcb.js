/**
 * MCB Investment Management (MCB Funds / Alhamra):
 *   Date | Nature | Units Inflow/(Outflow) | Rate | Gross Amount | FEL/BEL Load Amount | %age | Net Amount Inflow/(Outflow) | Balance Units
 *
 * A redemption is two dated rows: "iPayment-…" / "APP REDEMPTION" (units,
 * rate, gross) followed by "CGT*" (CGT in brackets under Gross, and the net
 * payout under Net Amount). Descriptions wrap over several undated lines and
 * may continue at the top of the next page. The trailing number of a wrapped
 * description ("…-UBL-148033") is the transaction reference.
 */
import {
  anchorsFrom, assignCells, classifyLabel, component, isDate, isFigure, makeEvent, makeSection, refFrom, signOf,
} from './common.js';

const COLS = [
  { key: 'units', re: /^units$/i },
  { key: 'rate', re: /^rate$/i },
  { key: 'gross', re: /^gross$/i },
  { key: 'load', re: /load/i },
  { key: 'net', re: /^net amount$/i },
  { key: 'balance', re: /^balance units$/i },
];
const SUB_COLS = [{ key: 'loadPct', re: /^%age$/i }];

/**
 * MCB prints a negative running balance as two cells, "-" and ".0001"
 * (a full redemption that rounds the balance just below zero). The dash is
 * the number's sign, not an empty cell.
 */
function joinDetachedMinus(cells) {
  const out = [];
  for (let i = 0; i < cells.length; i++) {
    const c = cells[i];
    const next = cells[i + 1];
    if (/^-$/.test(c.text) && next && /^[\d.,]+$/.test(next.text) && i === cells.length - 2) {
      out.push({ text: `-${next.text}`, x0: c.x0, x1: next.x1 });
      i++;
    } else {
      out.push(c);
    }
  }
  return out;
}

export function parseMcb(pages) {
  const out = { statement: { amc_name_printed: 'MCB Investment Management Limited', period_from_text: null, period_to_text: null }, sections: [], events: [], skipped_lines: [] };
  const lines = pages.flat();

  // "Statement Period … To OCT-31-2026" with the start date on its own line.
  const all = lines.map((l) => l.text).join('\n');
  const dates = [...all.matchAll(/\b([A-Z]{3}-\d{2}-\d{4})\b/g)].map((m) => m[1]);
  if (dates.length >= 2) {
    const toIdx = lines.findIndex((l) => /Statement Period/i.test(l.text));
    const nearby = lines.slice(Math.max(0, toIdx), toIdx + 3).map((l) => l.text).join(' ');
    const ds = [...nearby.matchAll(/\b([A-Z]{3}-\d{2}-\d{4})\b/g)].map((m) => m[1]);
    if (ds.length >= 2) {
      const sorted = ds.sort((a, b) => Date.parse(a) - Date.parse(b));
      out.statement.period_from_text = sorted[0];
      out.statement.period_to_text = sorted[sorted.length - 1];
    }
  }

  let anchors = null;
  let labelMaxX = 0;
  let natureX = 86;
  let section = null;
  let last = null;            // last event, to attach wrapped description lines
  let lastDesc = [];

  const finishDesc = () => {
    if (last && lastDesc.length) last.external_ref_text = last.external_ref_text ?? refFrom(lastDesc);
    lastDesc = [];
  };

  for (const l of lines) {
    const first = l.cells[0]?.text ?? '';
    if (/^Date$/i.test(first) && l.cells.some((c) => /^Nature$/i.test(c.text))) {
      // Page header repeats on every page; recompute anchors (layouts can shift).
      const pageLines = pages[l.page - 1];
      const at = pageLines.indexOf(l);
      anchors = [...anchorsFrom([l], COLS), ...anchorsFrom(pageLines.slice(at + 1, at + 4), SUB_COLS)];
      labelMaxX = (anchors.find((a) => a.key === 'units')?.x0 ?? 165) - 20;
      // Descriptions start a little left of the "Nature" header.
      natureX = Math.min(l.cells.find((c) => /^Nature$/i.test(c.text))?.x0 ?? 118, 118) - 32;
      continue;
    }
    if (!anchors) continue;
    if (/^Registration\s*#|^MCB Investment Management|^Generated By|^Page \d/i.test(l.text.trim())) continue;
    if (/^(Amount|Inflow\/\(Outflow\)|Rs\.)$/i.test(first)) continue;

    // Fund header: "MCB CASH MANAGEMENT OPTIMIZER    GROWTH" (repeats per page).
    // The unit-class cell far to the right is what distinguishes it from a
    // wrapped, all-caps description line such as the holder's name.
    if (!isDate(first) && /^[A-Z][A-Z0-9 &().-]+$/.test(first) && l.cells.length === 2
        && l.cells[1].x0 > (anchors.find((a) => a.key === 'load')?.x0 ?? 350)
        && /^(?:GROWTH|INCOME|DIVIDEND|BONUS|CLASS|TYPE|PLAN|CUMULATIVE|ACCUMULATION)\b/i.test(l.cells[1].text)) {
      const unitClass = l.cells[1]?.text ?? null;
      if (!section || section.fund_name_printed !== first || section.unit_class_printed !== unitClass) {
        finishDesc();
        section = out.sections.find((s) => s.fund_name_printed === first && s.unit_class_printed === unitClass)
          ?? makeSection(`s${out.sections.length + 1}`, first, unitClass);
        if (!out.sections.includes(section)) out.sections.push(section);
      }
      continue;
    }
    if (!section) continue;

    // Valuation: "Value of ABBR  .0001  Units based on Repurchase price of Rs. 106.1561 as on 30 OCT 2026 is Rs. .01"
    const v = l.text.match(/^\s*Value of\s+\S+\s+([\d.,]+)\s+Units based on Repurchase price of Rs\.\s+([\d.,]+)\s+as on\s+(\d{1,2} [A-Z]{3} \d{4})\s+is Rs\.\s+([\d.,]+)/i);
    if (v) {
      finishDesc();
      last = null;   // nothing after a fund's valuation line is a description
      section.closing_units_text = v[1];
      section.closing_line_id = l.id;
      section.valuation_price_text = v[2];
      section.valuation_date_text = v[3];
      section.valuation_value_text = v[4];
      section.valuation_line_id = l.id;
      continue;
    }
    if (/^Total Investment Value/i.test(first)) { finishDesc(); last = null; continue; }

    if (!isDate(first)) {
      // Wrapped description of the previous row (possibly across a page
      // break): text confined to the Nature column, right of the date.
      if (last && l.cells.every((c) => c.x0 >= natureX - 12 && c.x0 < labelMaxX + 20)) {
        last.line_ids.push(l.id);
        lastDesc.push(l.cells.map((c) => c.text).join(' '));
      }
      continue;
    }

    finishDesc();
    const labelCells = l.cells.slice(1).filter((c) => c.x0 < labelMaxX);
    const label = labelCells.map((c) => c.text).join(' ').trim();
    const { cols, unassigned } = assignCells(joinDetachedMinus(l.cells.slice(1).filter((c) => c.x0 >= labelMaxX)), anchors, { accept: isFigure });

    if (/^Last Balance$/i.test(label)) {
      section.opening_units_text = cols.balance ?? null;
      section.opening_line_id = l.id;
      last = null;
      continue;
    }

    const prev = out.events[out.events.length - 1];
    if (/^CGT\*?$/i.test(label) && prev && prev.section_id === section.section_id
        && prev.trade_date_text === first && signOf(prev.units_text) < 0 && !cols.units) {
      prev.components.push(component('cgt', cols.gross, label, l.id));
      if (cols.net) prev.net_amount_text = cols.net;
      prev.line_ids.push(l.id);
      prev.labels_printed.push(label);
      last = prev;
      continue;
    }

    const sign = signOf(cols.units);
    const type = classifyLabel(label.replace(/\s*-\s*$/, ''), { unitsSign: sign });
    const ev = makeEvent({
      section: section.section_id,
      primary: l.id,
      labels: [label.replace(/\s*-\s*$/, '')],
      type,
      date: first,
      units: cols.units, nav: cols.rate, gross: cols.gross, net: cols.net, balance: cols.balance,
      components: [component(sign < 0 ? 'back_load' : 'front_load', cols.load, 'FEL/BEL Load', l.id)],
      reason: unassigned.length ? `Unplaced figures: ${unassigned.join(', ')}` : null,
      confidence: unassigned.length || type === 'unknown' ? 'low' : 'high',
    });
    out.events.push(ev);
    last = ev;
  }
  finishDesc();
  return out;
}
